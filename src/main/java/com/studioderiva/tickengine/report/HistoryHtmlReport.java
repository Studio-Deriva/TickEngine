package com.studioderiva.tickengine.report;

import static com.studioderiva.tickengine.report.HtmlReport.escape;
import static com.studioderiva.tickengine.report.HtmlReport.format;
import static com.studioderiva.tickengine.report.HtmlReport.stat;

import com.studioderiva.tickengine.config.TickEngineConfig;
import com.studioderiva.tickengine.history.HistoryEntry;
import java.nio.file.Path;
import java.time.Instant;
import java.time.ZoneId;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Locale;
import java.util.concurrent.CompletableFuture;
import net.minecraft.server.MinecraftServer;

/** Self-contained HTML page of the history: a chart of the tick time and every peak with its details. */
public final class HistoryHtmlReport {
	private static final DateTimeFormatter TIME = DateTimeFormatter.ofPattern("MM-dd HH:mm").withZone(ZoneId.systemDefault());
	private static final int CHART_WIDTH = 1000;
	private static final int CHART_HEIGHT = 220;
	private static final int CHART_LEFT = 44;
	private static final int CHART_BOTTOM = 24;

	private HistoryHtmlReport() {
	}

	/** {@code entries}: oldest first. Renders on the calling thread, writes on the IO pool. */
	public static CompletableFuture<Path> writeAsync(MinecraftServer server, List<HistoryEntry> entries, int hours, long nowMillis) {
		return HtmlReport.write(server, "tickengine-history-" + HtmlReport.FILE_TIME.format(Instant.ofEpochMilli(nowMillis)) + ".html",
			render(entries, hours, nowMillis));
	}

	static String render(List<HistoryEntry> entries, int hours, long nowMillis) {
		List<HistoryEntry> periods = entries.stream().filter(entry -> entry.kind().equals(HistoryEntry.PERIOD)).toList();
		List<HistoryEntry> peaks = periods.stream().filter(HistoryEntry::isPeak).toList();
		List<HistoryEntry> sessions = entries.stream().filter(entry -> entry.kind().equals(HistoryEntry.SESSION)).toList();

		StringBuilder html = new StringBuilder(32_768);
		HtmlReport.head(html, "TickEngine history");
		html.append("<h1>TickEngine history</h1>\n<div class=\"muted\">Last ").append(hours).append(" h, until ")
			.append(HtmlReport.DISPLAY_TIME.format(Instant.ofEpochMilli(nowMillis))).append("</div>\n");

		long ticks = periods.stream().mapToLong(HistoryEntry::ticks).sum();
		double average = ticks == 0 ? 0 : periods.stream().mapToDouble(entry -> entry.avgMs() * entry.ticks()).sum() / ticks;
		HistoryEntry worst = periods.stream().max((a, b) -> Double.compare(a.avgMs(), b.avgMs())).orElse(null);
		HistoryEntry longest = periods.stream().max((a, b) -> Double.compare(a.maxMs(), b.maxMs())).orElse(null);
		html.append("<div class=\"stats\">\n");
		stat(html, "Periods recorded", Integer.toString(periods.size()));
		stat(html, "Average tick", format(average) + " ms");
		stat(html, "Worst period", worst == null ? "-" : format(worst.avgMs()) + " ms at " + TIME.format(Instant.ofEpochMilli(worst.endMillis())));
		stat(html, "Longest tick", longest == null ? "-" : format(longest.maxMs()) + " ms at " + TIME.format(Instant.ofEpochMilli(longest.endMillis())));
		stat(html, "Peaks", Integer.toString(peaks.size()));
		stat(html, "Detailed sessions", Integer.toString(sessions.size()));
		html.append("</div>\n");

		html.append("<h2>Tick time</h2>\n<p class=\"muted\">Average tick per period (line) and the peak threshold of "
			+ TickEngineConfig.historyPeakAverageMspt + " ms (dashed). Red dots are peaks; hover one for its time and "
			+ "values. Gaps are times when the server was off or paused.</p>\n");
		chart(html, periods, nowMillis - hours * 3_600_000L, nowMillis);

		html.append("<h2>Peaks</h2>\n<p class=\"muted\">A period is a peak when its average tick reaches ")
			.append(TickEngineConfig.historyPeakAverageMspt).append(" ms, one tick reaches ").append(TickEngineConfig.historyPeakTickMs)
			.append(" ms, or auto-tuning goes above level ").append(TickEngineConfig.historyPeakTuningLevel)
			.append(". What the light profiler saw is under each one (it measures one tick in 20).</p>\n");
		entryTable(html, peaks.reversed());
		if (!sessions.isEmpty()) {
			html.append("<h2>Detailed sessions during peaks</h2>\n<p class=\"muted\">Started by <code>history.profilePeaks</code>: "
				+ "every tick measured for a minute.</p>\n");
			entryTable(html, sessions.reversed());
		}
		html.append("""
			<footer class="muted">
			Times are the end of each period, in the server's time zone. History files are in tickengine/history and
			are deleted after history.keepDays days. Generated by TickEngine (Studio Deriva).
			</footer>
			</main>
			</body>
			</html>
			""");
		return html.toString();
	}

	private static void chart(StringBuilder html, List<HistoryEntry> periods, long fromMillis, long toMillis) {
		if (periods.isEmpty()) {
			html.append("<p class=\"muted\">No data yet.</p>\n");
			return;
		}
		double top = TickEngineConfig.historyPeakAverageMspt * 1.5;
		for (HistoryEntry entry : periods) {
			top = Math.max(top, entry.avgMs());
		}
		top = Math.ceil(top / 10) * 10;
		double plotWidth = CHART_WIDTH - CHART_LEFT - 8;
		double plotHeight = CHART_HEIGHT - CHART_BOTTOM - 8;
		html.append("<div class=\"table-wrap\" style=\"padding:8px\"><svg viewBox=\"0 0 ").append(CHART_WIDTH).append(' ')
			.append(CHART_HEIGHT).append("\" width=\"100%\" role=\"img\" aria-label=\"Average tick time over time\" "
				+ "style=\"display:block\">\n");
		// Grid lines at quarters of the scale, with their values.
		for (int i = 0; i <= 4; i++) {
			double value = top * i / 4;
			double y = 8 + plotHeight - plotHeight * i / 4;
			html.append(String.format(Locale.ROOT, "<line x1=\"%d\" x2=\"%d\" y1=\"%.1f\" y2=\"%.1f\" stroke=\"var(--line)\"/>"
				+ "<text x=\"%d\" y=\"%.1f\" font-size=\"11\" text-anchor=\"end\" fill=\"var(--muted)\">%s</text>\n",
				CHART_LEFT, CHART_WIDTH - 8, y, y, CHART_LEFT - 6, y + 4, format(value)));
		}
		double threshold = 8 + plotHeight - plotHeight * TickEngineConfig.historyPeakAverageMspt / top;
		html.append(String.format(Locale.ROOT, "<line x1=\"%d\" x2=\"%d\" y1=\"%.1f\" y2=\"%.1f\" stroke=\"#d33\" "
			+ "stroke-dasharray=\"5 4\"/>\n", CHART_LEFT, CHART_WIDTH - 8, threshold, threshold));
		// Time labels at the start, middle and end.
		for (int i = 0; i <= 2; i++) {
			long time = fromMillis + (toMillis - fromMillis) * i / 2;
			String anchor = i == 0 ? "start" : i == 1 ? "middle" : "end";
			html.append(String.format(Locale.ROOT, "<text x=\"%.1f\" y=\"%d\" font-size=\"11\" text-anchor=\"%s\" "
				+ "fill=\"var(--muted)\">%s</text>\n", CHART_LEFT + plotWidth * i / 2, CHART_HEIGHT - 6, anchor,
				TIME.format(Instant.ofEpochMilli(time))));
		}
		StringBuilder line = new StringBuilder();
		StringBuilder dots = new StringBuilder();
		long previousEnd = 0;
		for (HistoryEntry entry : periods) {
			double x = CHART_LEFT + plotWidth * (entry.endMillis() - fromMillis) / (double) Math.max(1, toMillis - fromMillis);
			double y = 8 + plotHeight - plotHeight * Math.min(entry.avgMs(), top) / top;
			// A gap longer than three periods (server off or paused) breaks the line.
			boolean gap = previousEnd == 0 || entry.endMillis() - previousEnd > entry.seconds() * 3000L;
			line.append(gap ? " M" : " L").append(String.format(Locale.ROOT, "%.1f %.1f", x, y));
			previousEnd = entry.endMillis();
			if (entry.isPeak()) {
				dots.append(String.format(Locale.ROOT, "<circle cx=\"%.1f\" cy=\"%.1f\" r=\"4\" fill=\"#d33\"><title>", x, y))
					.append(escape(TIME.format(Instant.ofEpochMilli(entry.endMillis())) + ": avg " + format(entry.avgMs())
						+ " ms, longest " + format(entry.maxMs()) + " ms, auto-tuning " + entry.tuningLevel() + " ("
						+ String.join(", ", entry.peaks()) + ")"))
					.append("</title></circle>\n");
			}
		}
		html.append("<path d=\"").append(line.toString().trim()).append("\" fill=\"none\" stroke=\"var(--bar)\" stroke-width=\"1.5\"/>\n")
			.append(dots).append("</svg></div>\n");
	}

	private static void entryTable(StringBuilder html, List<HistoryEntry> entries) {
		if (entries.isEmpty()) {
			html.append("<p class=\"muted\">None.</p>\n");
			return;
		}
		html.append("<div class=\"table-wrap\"><table>\n<tr><th>Ended</th><th>Why</th><th>Avg tick</th><th>Longest tick</th>"
			+ "<th>TPS</th><th>Players</th><th>Entities</th><th>Chunks</th><th>Auto-tuning</th></tr>\n");
		for (HistoryEntry entry : entries.subList(0, Math.min(HtmlReport.MAX_ROWS, entries.size()))) {
			html.append("<tr><td>").append(TIME.format(Instant.ofEpochMilli(entry.endMillis()))).append("</td><td>")
				.append(escape(String.join(", ", entry.peaks()))).append(entry.emergency() ? ", emergency" : "")
				.append("</td><td class=\"num\">").append(format(entry.avgMs())).append(" ms</td><td class=\"num\">")
				.append(format(entry.maxMs())).append(" ms</td><td class=\"num\">").append(format(entry.tps()))
				.append("</td><td class=\"num\">").append(entry.players()).append("</td><td class=\"num\">").append(entry.entities())
				.append("</td><td class=\"num\">").append(entry.chunks()).append("</td><td class=\"num\">").append(entry.tuningLevel())
				.append("</td></tr>\n");
			// Its own row across the table: a narrow cell would make the opened details very tall.
			html.append("<tr><td colspan=\"9\" style=\"white-space:normal\">");
			detail(html, entry.detail());
			html.append("</td></tr>\n");
		}
		html.append("</table></div>\n");
	}

	private static void detail(StringBuilder html, HistoryEntry.Detail detail) {
		if (detail == null) {
			html.append("<span class=\"muted\">no profiler data</span>");
			return;
		}
		String summary = detail.mods().isEmpty() ? detail.source()
			: detail.mods().get(0).name() + " " + format(detail.mods().get(0).msPerTick()) + " ms/tick";
		html.append("<details><summary>What took the time: ").append(escape(summary)).append("</summary><div>")
			.append("<div class=\"muted\">").append(escape(detail.source())).append("</div><b>Mods</b><br>");
		detail.mods().forEach(mod -> html.append(escape(mod.name())).append(" ").append(format(mod.msPerTick())).append(" ms/tick<br>"));
		html.append("<b>Types</b><br>");
		detail.types().forEach(type -> {
			html.append("<code>").append(escape(type.id())).append("</code> ").append(escape(type.category().toLowerCase(Locale.ROOT)))
				.append(' ').append(format(type.msPerTick())).append(" ms/tick");
			if (type.dimension() != null) {
				html.append(" <code>").append(escape(type.dimension())).append(' ').append(type.x()).append(' ')
					.append(type.y()).append(' ').append(type.z()).append("</code>");
			}
			html.append("<br>");
		});
		html.append("<b>Chunks</b><br>");
		detail.chunks().forEach(chunk -> html.append("<code>").append(escape(chunk.dimension())).append(' ').append(chunk.x())
			.append(' ').append(chunk.y()).append(' ').append(chunk.z()).append("</code> ").append(format(chunk.msPerTick()))
			.append(" ms/tick, mostly <code>").append(escape(chunk.top())).append("</code><br>"));
		html.append("</div></details>");
	}
}
