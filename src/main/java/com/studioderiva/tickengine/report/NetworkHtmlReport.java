package com.studioderiva.tickengine.report;

import static com.studioderiva.tickengine.report.HtmlReport.MAX_ROWS;
import static com.studioderiva.tickengine.report.HtmlReport.bar;
import static com.studioderiva.tickengine.report.HtmlReport.escape;
import static com.studioderiva.tickengine.report.HtmlReport.format;
import static com.studioderiva.tickengine.report.HtmlReport.formatSeconds;
import static com.studioderiva.tickengine.report.HtmlReport.stat;

import com.studioderiva.tickengine.network.NetworkSnapshot;
import com.studioderiva.tickengine.network.NetworkSource;
import java.nio.file.Path;
import java.time.Instant;
import java.util.List;
import java.util.concurrent.CompletableFuture;
import java.util.stream.Collectors;
import net.minecraft.server.MinecraftServer;

/** Writes a self-contained HTML report for a network profiling session. */
public final class NetworkHtmlReport {
	private NetworkHtmlReport() {
	}

	/** Renders on the calling (server) thread and writes on the IO pool, like {@link HtmlReport}. */
	public static CompletableFuture<Path> writeAsync(MinecraftServer server, NetworkSnapshot snapshot) {
		return HtmlReport.write(server, "tickengine-network-"
			+ HtmlReport.FILE_TIME.format(Instant.ofEpochMilli(snapshot.startMillis)) + ".html", render(server, snapshot));
	}

	static String render(MinecraftServer server, NetworkSnapshot snapshot) {
		StringBuilder html = new StringBuilder(32_768);
		HtmlReport.head(html, "TickEngine network report");
		html.append("<h1>TickEngine network report</h1>\n");
		html.append("<div class=\"muted\">").append(escape(snapshot.label)).append(" &middot; started ")
			.append(HtmlReport.DISPLAY_TIME.format(Instant.ofEpochMilli(snapshot.startMillis))).append("</div>\n");

		html.append("<div class=\"stats\">\n");
		stat(html, "Duration", formatSeconds(snapshot.durationMillis));
		stat(html, "Players online", Integer.toString(server.getPlayerCount()));
		stat(html, "Packets sent", format(snapshot.perSecond(snapshot.packets)) + " /s");
		stat(html, "Upload", NetworkSnapshot.formatBytes(snapshot.perSecond(snapshot.wireBytes)) + "/s");
		stat(html, "Total sent", NetworkSnapshot.formatBytes(snapshot.wireBytes));
		stat(html, "Saved by compression", format(snapshot.compressionSaving()) + " %");
		html.append("</div>\n");
		if (snapshot.compressionUnmeasured > 0) {
			html.append("<p class=\"muted\">Another mod compresses the packets (").append(snapshot.compressionUnmeasured)
				.append(" of them): their sent size is shown before compression.</p>\n");
		}

		html.append("<h2>By mod</h2>\n");
		modTable(html, snapshot);
		html.append("<h2>By source</h2>\n");
		sourceTable(html, snapshot, snapshot.sources);
		html.append("<h2>By packet type</h2>\n");
		packetTable(html, snapshot);
		html.append("<h2>By chunk</h2>\n");
		chunkTable(html, snapshot);

		html.append("""
			<footer class="muted">
			Sizes are what the server sent to all players together: a packet sent to three players counts three
			times. &ldquo;Sent&rdquo; is what goes on the wire, after compression and with the length every packet
			carries; &ldquo;raw&rdquo; is the packet itself before compression. Small packets are not compressed, so their
			sent size is a byte or two more than raw. A packet that sets blocks of several kinds is split between them by
			how many it sets, and counts as one packet for each. A source belongs to the mod
			that registered it, so a vanilla mob spawned by a modded farm counts as Minecraft: the chunk table shows
			where the traffic comes from. Packets about the world itself (chunks, light) and other vanilla packets
			(player movement, chat, inventory...) have no chunk of their own. Generated by TickEngine (Studio Deriva).
			</footer>
			</main>
			</body>
			</html>
			""");
		return html.toString();
	}

	private static void modTable(StringBuilder html, NetworkSnapshot snapshot) {
		List<NetworkSnapshot.ModEntry> mods = snapshot.mods();
		if (mods.isEmpty()) {
			html.append("<p class=\"muted\">No data.</p>\n");
			return;
		}
		double top = snapshot.percent(mods.get(0).wireBytes());
		html.append("<div class=\"table-wrap\"><table>\n<tr><th>Mod</th><th>Namespace</th><th>Sources</th>"
			+ "<th>Packets/s</th><th>Sent/s</th><th>Raw/s</th><th>% of sent</th><th></th></tr>\n");
		for (NetworkSnapshot.ModEntry mod : mods.subList(0, Math.min(MAX_ROWS, mods.size()))) {
			double percent = snapshot.percent(mod.wireBytes());
			html.append("<tr><td>").append(escape(mod.displayName())).append("</td><td><code>")
				.append(escape(mod.namespace())).append("</code></td><td class=\"num\">").append(mod.sources())
				.append("</td>");
			traffic(html, snapshot, mod.packets(), mod.wireBytes(), mod.rawBytes());
			html.append("<td class=\"num\">").append(format(percent)).append("</td><td>");
			bar(html, percent, top);
			html.append("</td></tr>\n");
		}
		html.append("</table></div>\n");
	}

	private static void sourceTable(StringBuilder html, NetworkSnapshot snapshot, List<NetworkSnapshot.SourceEntry> sources) {
		if (sources.isEmpty()) {
			html.append("<p class=\"muted\">No data.</p>\n");
			return;
		}
		double top = snapshot.percent(sources.get(0).wireBytes());
		html.append("<div class=\"table-wrap\"><table>\n<tr><th>Kind</th><th>Source</th><th>Packets/s</th><th>Sent/s</th>"
			+ "<th>Raw/s</th><th>% of sent</th><th></th><th>Mostly as</th></tr>\n");
		for (NetworkSnapshot.SourceEntry entry : sources.subList(0, Math.min(MAX_ROWS, sources.size()))) {
			double percent = snapshot.percent(entry.wireBytes());
			html.append("<tr><td>").append(escape(entry.source().kind().displayName)).append("</td><td><code>")
				.append(escape(entry.source().id())).append("</code></td>");
			traffic(html, snapshot, entry.packets(), entry.wireBytes(), entry.rawBytes());
			html.append("<td class=\"num\">").append(format(percent)).append("</td><td>");
			bar(html, percent, top);
			html.append("</td><td><code>").append(escape(entry.topPackets().stream()
				.map(share -> share.packet() + " " + format(entry.wireBytes() == 0 ? 0
					: share.wireBytes() * 100.0 / entry.wireBytes()) + "%")
				.collect(Collectors.joining(", ")))).append("</code></td></tr>\n");
		}
		html.append("</table></div>\n");
	}

	private static void packetTable(StringBuilder html, NetworkSnapshot snapshot) {
		List<NetworkSnapshot.PacketEntry> packets = snapshot.packetTypes;
		if (packets.isEmpty()) {
			html.append("<p class=\"muted\">No data.</p>\n");
			return;
		}
		double top = snapshot.percent(packets.get(0).wireBytes());
		html.append("<div class=\"table-wrap\"><table>\n<tr><th>Packet</th><th>Packets/s</th><th>Sent/s</th>"
			+ "<th>Raw/s</th><th>Avg size</th><th>% of sent</th><th></th></tr>\n");
		for (NetworkSnapshot.PacketEntry entry : packets.subList(0, Math.min(MAX_ROWS, packets.size()))) {
			double percent = snapshot.percent(entry.wireBytes());
			html.append("<tr><td><code>").append(escape(entry.id())).append("</code></td>");
			traffic(html, snapshot, entry.packets(), entry.wireBytes(), entry.rawBytes());
			html.append("<td class=\"num\">").append(NetworkSnapshot.formatBytes(entry.packets() == 0 ? 0
				: entry.wireBytes() / (double) entry.packets())).append("</td><td class=\"num\">")
				.append(format(percent)).append("</td><td>");
			bar(html, percent, top);
			html.append("</td></tr>\n");
		}
		html.append("</table></div>\n");
	}

	private static void chunkTable(StringBuilder html, NetworkSnapshot snapshot) {
		List<NetworkSnapshot.ChunkEntry> chunks = snapshot.chunks;
		if (chunks.isEmpty()) {
			html.append("<p class=\"muted\">No data.</p>\n");
			return;
		}
		double top = snapshot.percent(chunks.get(0).wireBytes());
		html.append("<div class=\"table-wrap\"><table>\n<tr><th>Dimension</th><th>Chunk</th><th>Last packet at</th>"
			+ "<th>Packets/s</th><th>Sent/s</th><th>% of sent</th><th></th><th>Mostly</th></tr>\n");
		for (NetworkSnapshot.ChunkEntry entry : chunks.subList(0, Math.min(MAX_ROWS, chunks.size()))) {
			double percent = snapshot.percent(entry.wireBytes());
			html.append("<tr><td><code>").append(escape(entry.dimension().identifier().toString()))
				.append("</code></td><td class=\"num\">").append(entry.x()).append(", ").append(entry.z())
				.append("</td><td><code>").append(entry.spot() == null ? "" : entry.spot().x() + " " + entry.spot().y() + " "
					+ entry.spot().z()).append("</code></td>")
				.append("<td class=\"num\">").append(format(snapshot.perSecond(entry.packets()))).append("</td>")
				.append("<td class=\"num\">").append(NetworkSnapshot.formatBytes(snapshot.perSecond(entry.wireBytes())))
				.append("</td><td class=\"num\">").append(format(percent)).append("</td><td>");
			bar(html, percent, top);
			NetworkSource source = entry.topSource();
			html.append("</td><td><code>").append(source == null ? "" : escape(source.label())).append("</code></td></tr>\n");
		}
		html.append("</table></div>\n");
	}

	private static void traffic(StringBuilder html, NetworkSnapshot snapshot, long packets, long wire, long raw) {
		html.append("<td class=\"num\">").append(format(snapshot.perSecond(packets))).append("</td><td class=\"num\">")
			.append(NetworkSnapshot.formatBytes(snapshot.perSecond(wire))).append("</td><td class=\"num\">")
			.append(NetworkSnapshot.formatBytes(snapshot.perSecond(raw))).append("</td>");
	}
}
